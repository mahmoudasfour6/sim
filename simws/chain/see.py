"""Single event to circuit (contract A10): deposited energy -> charge -> current pulse -> critical charge -> P.

    from simws.chain import see as C
    q = C.charge_C(1.6e6)                                         # 1.6 MeV in silicon -> about 70 fC
    pulse = C.double_exponential(q, 1e-12, 10e-12)                # Messenger's pulse as a PWL source
    qc = C.critical_charge(hub, circuit, "n", 0.5, 1e-12, 10e-12, q_low_C=1e-15, q_high_C=2e-14)
    up = C.upset_probability(hub.result(see_result_id), qc)       # probability per particle of an upset

The assumptions are the sensitive-volume model's: every pair generated in the SV is collected at one node, with a
pulse shape whose time constants come from TCAD or measurement (inputs here, never defaults).
"""
from __future__ import annotations

import math
from typing import Any, Dict

import numpy as np

Q_E = 1.602176634e-19                 # C, CODATA 2018 (exact)
# Mean energy per electron-hole pair in silicon: F. Scholze, H. Rabus, G. Ulm, J. Appl. Phys. 84(5), 2926 (1998),
# doi 10.1063/1.368398: 3.66 +- 0.03 eV (photons 50 to 1500 eV). Used as the room-temperature value.
PAIR_ENERGY_SI_EV = 3.66
OUTSIDE_FLAG = "upset:outside_histogram"


def charge_C(edep_eV, pair_energy_eV: float = PAIR_ENERGY_SI_EV):
    """Charge of the pairs generated by a deposit of edep_eV (scalar or array)."""
    return np.asarray(edep_eV, float) / pair_energy_eV * Q_E if np.ndim(edep_eV) else \
        float(edep_eV) / pair_energy_eV * Q_E


def edep_eV(charge, pair_energy_eV: float = PAIR_ENERGY_SI_EV):
    """Deposit that generates `charge` coulombs (inverse of charge_C)."""
    return np.asarray(charge, float) / Q_E * pair_energy_eV if np.ndim(charge) else \
        float(charge) / Q_E * pair_energy_eV


def double_exponential(charge: float, tau_rise_s: float, tau_fall_s: float, delay_s: float = 0.0,
                       n_points: int = 2001):
    """Messenger's double-exponential current pulse (IEEE TNS 29(6), 2024, 1982) as a PWL whose trapezoidal
    integral is exactly `charge`. Times t_j = delay + 20 tau_fall (j/(n-1))^2."""
    from simws.spec.circuit import Pwl
    if not charge > 0:
        raise ValueError("double_exponential: charge must be > 0")
    if not 0 < tau_rise_s < tau_fall_s:
        raise ValueError("double_exponential: need 0 < tau_rise_s < tau_fall_s")
    if not delay_s >= 0:
        raise ValueError("double_exponential: delay_s must be >= 0")
    if not 50 <= int(n_points) <= 5000:
        raise ValueError("double_exponential: 50 <= n_points <= 5000")
    n = int(n_points)
    s = 20.0 * tau_fall_s * (np.arange(n) / (n - 1)) ** 2          # time since the start of the pulse
    i = (np.exp(-s / tau_fall_s) - np.exp(-s / tau_rise_s)) / (tau_fall_s - tau_rise_s)
    i[-1] = 0.0
    i *= charge / float(np.trapezoid(i, s))
    return Pwl(points=[(float(delay_s + t), float(v)) for t, v in zip(s, i)])


def inject(problem, node: str, pulse, polarity: str = "discharge", name: str = "set"):
    """A copy of a transient CircuitProblem with an isource `name` carrying `pulse` at `node`."""
    from simws.spec.circuit import CircuitProblem, Element
    if problem.analysis.kind != "tran":
        raise ValueError("inject: the circuit needs a transient analysis")
    nodes = {n.lower() for e in problem.elements for n in e.nodes}
    if node.lower() not in nodes:
        raise ValueError(f"inject: node '{node}' is not in the circuit")
    if any(e.name.lower() == name.lower() for e in problem.elements):
        raise ValueError(f"inject: an element is already named '{name}'")
    if polarity not in ("discharge", "charge"):
        raise ValueError("inject: polarity is 'discharge' or 'charge'")
    d = problem.model_dump(mode="json")
    src = Element(name=name, kind="isource", nodes=[node, "0"] if polarity == "discharge" else ["0", node],
                  value=0.0, pwl=pulse)
    d["elements"].append(src.model_dump(mode="json"))
    probe = f"v({node})"
    if not any(p.replace(" ", "").lower() == probe.lower() for p in d["probes"]):
        d["probes"].append(probe)
    return CircuitProblem.model_validate(d)


def _extreme(r, node: str, polarity: str) -> float:
    v = r.q(f"circuit.v.{node.lower()}").array()
    return float(np.min(v) if polarity == "discharge" else np.max(v))


def critical_charge(hub, problem, node: str, threshold_V: float, tau_rise_s: float, tau_fall_s: float,
                    q_low_C: float, q_high_C: float, delay_s: float = 0.0, polarity: str = "discharge",
                    rel_tol: float = 1e-3, max_runs: int = 60) -> Dict[str, Any]:
    """Smallest pulse charge that drives `node` to `threshold_V`, by bisection over circuit.ngspice jobs."""
    if not 0 < q_low_C < q_high_C:
        raise ValueError("critical_charge: need 0 < q_low_C < q_high_C")
    ids = []

    def upset(q: float) -> bool:
        p = inject(problem, node, double_exponential(q, tau_rise_s, tau_fall_s, delay_s), polarity)
        r = hub.submit("circuit.ngspice", params={"problem": p})
        if r.status != "ok":
            raise RuntimeError(f"critical_charge: circuit job for {q:.4e} C: {r.status}: {r.message}")
        ids.append(r.id)
        x = _extreme(r, node, polarity)
        return x <= threshold_V if polarity == "discharge" else x >= threshold_V

    lo, hi = float(q_low_C), float(q_high_C)
    if upset(lo):
        raise ValueError(f"critical_charge: q_low_C = {lo:.4e} C already upsets the node; lower it")
    if not upset(hi):
        raise ValueError(f"critical_charge: q_high_C = {hi:.4e} C does not upset the node; raise it")
    while (hi - lo) / hi > rel_tol:
        if len(ids) >= max_runs:
            raise RuntimeError(f"critical_charge: {max_runs} runs without reaching rel_tol {rel_tol:g}")
        mid = 0.5 * (lo + hi)
        if upset(mid):
            hi = mid
        else:
            lo = mid
    return {"qcrit_C": 0.5 * (lo + hi), "q_lo_C": lo, "q_hi_C": hi, "runs": len(ids), "result_ids": ids,
            "node": node, "threshold_V": float(threshold_V), "polarity": polarity, "tau_rise_s": float(tau_rise_s),
            "tau_fall_s": float(tau_fall_s)}


def upset_probability(see_result, qcrit: Dict[str, Any], pair_energy_eV: float = PAIR_ENERGY_SI_EV) -> Dict[str, Any]:
    """Probability per particle of depositing at least the critical charge, from a stored see.* result."""
    pa = see_result.q("see.p_above")
    thr = np.asarray(pa.axes[0].values, float)
    p = np.asarray(pa.array(), float)
    over = float(see_result.q("see.fraction_overflow").value)
    n = int(see_result.diagnostics["n_events"])
    # bin edges: the lower edges are the p_above thresholds; the upper limit follows from the last bin centre
    # (the midpoint for a linear histogram, the geometric mean for a log one)
    c = np.asarray(see_result.q("see.edep_spectrum").axes[0].values, float)
    lin = thr.size < 2 or abs(c[0] - 0.5 * (thr[0] + thr[1])) <= 1e-9 * abs(c[0])
    top = 2 * c[-1] - thr[-1] if lin else c[-1] ** 2 / thr[-1]
    edges = np.append(thr, top)
    pv = np.append(p, over)
    flags = []

    def at(e: float, flag: bool = False) -> float:
        if e < edges[0] or e > edges[-1]:
            if flag:                                   # A10.1: the flag is about E_crit only
                flags.append(OUTSIDE_FLAG)
            return 1.0 if e < edges[0] else over
        return float(np.interp(e, edges, pv))

    e_c = float(edep_eV(qcrit["qcrit_C"], pair_energy_eV))
    P = at(e_c, flag=True)
    P_low = at(float(edep_eV(qcrit["q_hi_C"], pair_energy_eV)))
    P_high = at(float(edep_eV(qcrit["q_lo_C"], pair_energy_eV)))
    pp = (P * n + 1) / (n + 2)
    return {"P": P, "P_low": P_low, "P_high": P_high, "sigma": math.sqrt(pp * (1 - pp) / n), "E_crit_eV": e_c,
            "n_events": n, "flags": sorted(set(flags))}
